/**
 * FormGuard — the checks a public form passes before it stores what a visitor typed.
 *
 * WHY THIS CLASS EXISTS
 * ---------------------
 * Between 23 July and 26 September 2026 a program used the home page's three
 * signup forms on 64 of 66 days. Of the 672 rows in email_signups, 654 came from
 * 41 internet addresses on two hosting companies' networks. The handler checked a
 * CSRF token and nothing else, and a program that loads the page first carries a
 * valid token. Every signup made the site send a confirmation message to the
 * address typed in, so the band's site mailed about 650 people who never asked.
 * Nothing noticed for ten weeks.
 *
 * The contact page and the support page each had checks of their own, written
 * three separate times, and each copy had a hole the others did not:
 *
 *   - the timer trusted a timestamp THE VISITOR SENDS, and skipped the check
 *     altogether when the field was missing (`$ts > 0 && ...`);
 *   - the trap fields were named `website` and `company_name`, which a browser's
 *     autofill fills in for a real person;
 *   - a tripped trap answered "success", so a real person caught by it was told
 *     to check an inbox that would never receive anything;
 *   - a refused sender was logged to the PHP error log as a fault, and on the
 *     contact form was shown "something went wrong on our end".
 *
 * Adding the missing checks to a fourth copy is how four copies come to disagree.
 * This is the one copy. Since 27 November 2026 it lives in the engine
 * (shared-platform core/), made from the band site's file of 26 November: the
 * platform's signup and every store use this file, and the band site and
 * offda9.com are to carry copies generated from it (pieces 4 and 6 of the form
 * checks; until then the band runs its own). Each repository's
 * tests/Unit/PublicFormsUseTheGuardTest.php fails the build when a public form
 * stores or mails what a visitor typed without passing through it.
 *
 * WHAT IT CHECKS, in this order
 * -----------------------------
 *   trap       a field no person can see or reach is filled in
 *   no_page    the form arrived without the page having been rendered in this
 *              session (a program posting straight at the handler)
 *   too_fast   it arrived sooner than MIN_SECONDS after the page was rendered.
 *              The render time is kept in the SESSION and never read from the
 *              request, so it cannot be forged or left out.
 *   no_script  the value a script copies into the form on a loaded page is
 *              missing or wrong (a program that sends the form as it parsed it)
 *   no_human   Cloudflare does not say a person sent it: the widget's token is
 *              missing, refused, or could not be checked (HumanCheck.php). Asked
 *              last of these, so a question is put to Cloudflare only for a
 *              submission the four checks above let through. Skipped while the
 *              site has no widget keys.
 * and, once the database is open:
 *   paused     the signup forms only: the site has stopped taking signups
 *              because the ones it took are not being confirmed (SignupBrake.php)
 * The per-sender limits stay with the handlers that had them (the engine's
 * checkSignupRateLimit(), a store's contact limit, CustomerAuth's account and
 * reset limits); the public-forms test requires one between the guard and the
 * write. The band's limit() and overLimit() count a sender's rows in the table
 * the form writes, and a store's customers row records no sender, so a store's
 * Create Account is limited in CustomerAuth instead (piece 2); they come into
 * this file with the band's contact and support forms, their first callers here
 * (piece 6).
 *
 * WHAT IT DID NOT DO, AND WHAT DOES NOW
 * -------------------------------------
 * The first four checks and the rate limit do not stop a program that drives a
 * real browser, slowly, from many addresses: the flood above never sent more
 * than eight signups in a minute, and its busiest address sent 45 in two months,
 * so a per-address limit alone would not have slowed it. Until 26 November 2026
 * that case was only made VISIBLE, by SignupVolume
 * (public/api/health/signup-volume.php). That day it happened again: two dozen
 * signups through the footer form, each from a different Tor exit, sent by an
 * automated Chrome that passed all of the above. Two things answer it now.
 * `no_human` asks Cloudflare, which is built to tell that Chrome from a fan's.
 * `paused` does not depend on telling anything: past ten unconfirmed signups in
 * a day the site takes no more, whoever is sending them.
 *
 * A REFUSAL IS TOLD AS A REFUSAL
 * ------------------------------
 * The visitor reads that the form was not taken and how to try again. A program
 * does not read the page, so honesty costs nothing, and a person caught by
 * mistake is never told to wait for mail that is not coming. Each refusal is one
 * line in logs/form-guard.jsonl, which is where "is the guard catching anything,
 * and is it catching people?" gets answered without asking anyone.
 *
 * WHAT A SITE HANDS IN
 * --------------------
 * configure(), once, where the site boots: the folder the logs go in (outside
 * every docroot), how to learn the visitor's address, and the transport the
 * human check asks Cloudflare through (HumanCheck.php, HOW CLOUDFLARE IS ASKED;
 * the engine's is SsrfGuard, core/HumanCheckTransport.php). Behind Cloudflare,
 * REMOTE_ADDR can be Cloudflare's own address; every refusal would then name
 * the same edge, and the human check would hand Cloudflare its own address as
 * the sender's. The engine's PublicBootstrap configures it with ClientIp, which
 * believes a forwarding header only from Cloudflare. The session and the
 * request come in on every call, so nothing here reads a global.
 *
 * PASSES
 * ------
 * Callers that are not a person's browser post real forms on purpose: the
 * nightly provers (with the rehearsal grant a server-side script mints: on the
 * platform's signup, and on a store's forms as that store's TEST sandbox), and,
 * from piece 4, od9's daily canary and the Discord bot. A browser driven by a
 * script gets no token from Cloudflare, so each carries a credential its site
 * checks before calling admit(), and says so with $pass. A pass skips the
 * Cloudflare question and nothing else: the trap, the page, the delay, the
 * proof, the brake and every limit still apply. Each use is one line in
 * logs/form-guard-passes.jsonl, and the health answer counts them
 * (countPasses()), so a pass that leaks shows as a count above the one or two
 * a day the provers make.
