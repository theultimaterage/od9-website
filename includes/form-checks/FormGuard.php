final class FormGuardRefused extends RuntimeException
{
    /** @var string one of FormGuard::REASONS */
    public string $reason;

    public function __construct(string $message, string $reason)
    {
        parent::__construct($message);
        $this->reason = $reason;
    }
}

final class FormGuard
{
    /** A person needs longer than this to read a form and type an address. */
    public const MIN_SECONDS = 3;

    public const SESSION_KEY = 'form_guard';

    /**
     * The trap. Named after nothing an autofill profile holds: `website`,
     * `company`, `phone` and their relatives are filled in for real people.
     */
    public const TRAP_FIELD = 'fg_ref';

    public const PROOF_FIELD = 'fg_proof';

    public const REASONS = ['trap', 'no_page', 'too_fast', 'no_script', 'no_human', 'paused'];

    public const REFUSED = "We couldn't take that just now. Please reload the page and try again.";
    /** One sentence for every way the human check says no, the outage included. */
    public const NO_HUMAN = "We couldn't confirm that a person sent this, so it was not taken. "
        . 'Please wait for the check above the button to finish, then try again.';

    /** Tests hand in a check of their own. Null means this server's, read from its environment. */
    public static ?HumanCheck $humanCheckOverride = null;

    /** The human check every guarded form on this server shares. */
    public static function humanCheck(): HumanCheck
    {
        return self::$humanCheckOverride ?? HumanCheck::fromEnvironment(self::$humanCheckTransport);
    }

    /** How the human check reaches Cloudflare on this site; null asks nobody and refuses. */
    private static ?Closure $humanCheckTransport = null;

    /** The folder both logs go in; null until the site says (then the engine's logs/). */
    private static ?string $logDirectory = null;

    /** How this site reads the visitor's address; null means REMOTE_ADDR as PHP has it. */
    private static ?Closure $clientIp = null;

    /**
     * What the guard needs from the site it runs on (WHAT A SITE HANDS IN above),
     * said once where the site boots. $clientIp is called with the request's
     * server array and returns the visitor's address. $humanCheckTransport is
     * how the human check asks Cloudflare (HumanCheck.php, HOW CLOUDFLARE IS ASKED).
     */
    public static function configure(string $logDirectory, ?callable $clientIp = null, ?callable $humanCheckTransport = null): void
    {
        $logDirectory = rtrim(trim($logDirectory), "/\\");
        if ($logDirectory === '') {
            throw new InvalidArgumentException('FormGuard::configure needs a folder for its logs');
        }
        self::$logDirectory = $logDirectory;
        self::$clientIp = $clientIp === null ? null : Closure::fromCallable($clientIp);
        self::$humanCheckTransport = $humanCheckTransport === null ? null : Closure::fromCallable($humanCheckTransport);
    }

    /**
     * The visitor's address as this site reads it, null when there is none. A
     * reader that fails must not take the page down with it: the failure goes to
     * the error log and the connection's own address stands in.
     */
    private static function clientIp(array $server): ?string
    {
        $connection = isset($server['REMOTE_ADDR']) && is_string($server['REMOTE_ADDR']) ? $server['REMOTE_ADDR'] : null;
        if (self::$clientIp === null) {
            return $connection;
        }
        try {
            $ip = (self::$clientIp)($server);
        } catch (Throwable $e) {
            error_log('FormGuard could not read the visitor\'s address, so the connection\'s stands in: ' . $e->getMessage());
            return $connection;
        }
        return is_string($ip) && $ip !== '' ? $ip : $connection;
    }

    /**
     * Remember that a page carrying guarded forms is being rendered now.
     *
     * Call it AFTER the page has handled a POST and BEFORE it prints its forms:
     * a POST is judged against the render that produced the form it came from,
     * so stamping first would make every submission look instant.
     */
    public static function open(array &$session, ?int $now = null): void
    {
        $state = $session[self::SESSION_KEY] ?? null;
        if (!is_array($state)) {
            $state = [];
        }
        if (!isset($state['proof']) || !is_string($state['proof']) || $state['proof'] === '') {
            $state['proof'] = bin2hex(random_bytes(16));
        }
        $state['opened_at'] = $now ?? time();
        $session[self::SESSION_KEY] = $state;
    }

    /**
     * The markup every guarded form carries: the trap, the proof field, a line
     * for a visitor whose browser runs no scripts and, while the human check is
     * on, the place its widget goes. Print it inside the <form>, just above the
     * button: the widget is the one part of this a visitor sees.
     */
    public static function fields(array $session): string
    {
        $proof = '';
        $state = $session[self::SESSION_KEY] ?? null;
        if (is_array($state) && isset($state['proof']) && is_string($state['proof'])) {
            $proof = $state['proof'];
        }
        $proof = htmlspecialchars($proof, ENT_QUOTES, 'UTF-8');

        return '<div style="position:absolute;left:-9999px;width:1px;height:1px;overflow:hidden;" aria-hidden="true">'
            . '<label>Leave this field empty <input type="text" name="' . self::TRAP_FIELD
            . '" value="" tabindex="-1" autocomplete="off"></label></div>'
            . '<input type="hidden" name="' . self::PROOF_FIELD . '" value="" data-fg="' . $proof . '">'
            . '<noscript><p>This form needs JavaScript switched on in your browser.</p></noscript>'
            . self::humanCheck()->widget();
    }

    /**
     * The script that copies the proof into every guarded form and, while the
     * human check is on, Cloudflare's script with the lines that place its
     * widgets. Print it once per page, anywhere after the forms or in the head:
     * it waits for the document.
     */
    public static function script(): string
    {
        return '<script>(function(){function arm(){var f=document.querySelectorAll(\'input[name="'
            . self::PROOF_FIELD . '"]\');for(var i=0;i<f.length;i++){f[i].value=f[i].getAttribute("data-fg")||"";}}'
            . 'if(document.readyState==="loading"){document.addEventListener("DOMContentLoaded",arm);}else{arm();}})();</script>'
            . self::humanCheck()->script();
    }

    /**
     * Judge one submission. Returns null when it may go on, or the reason it may
     * not. Pure: no clock but the one handed in, no database, no output.
     */
    public static function check(array $session, array $post, ?int $now = null): ?string
    {
        $trap = $post[self::TRAP_FIELD] ?? '';
        if (!is_string($trap) || trim($trap) !== '') {
            return 'trap';
        }

        $state = $session[self::SESSION_KEY] ?? null;
        if (!is_array($state)
            || !isset($state['opened_at'], $state['proof'])
            || !is_int($state['opened_at'])
            || !is_string($state['proof'])
            || $state['proof'] === '') {
            return 'no_page';
        }

        if ((($now ?? time()) - $state['opened_at']) < self::MIN_SECONDS) {
            return 'too_fast';
        }

        $proof = $post[self::PROOF_FIELD] ?? '';
        if (!is_string($proof) || !hash_equals($state['proof'], $proof)) {
            return 'no_script';
        }

        return null;
    }

    /**
     * check(), then the human check, for a page: a refusal is written to the log
     * and thrown, so the handler stops before it opens the database or reads
     * another field.
     *
     * The human check comes after check() on purpose. It is the one step that
     * leaves this server, so it is spent only on a submission that already has a
     * rendered page, a believable delay and the script's proof behind it; and the
     * `paused` and `rate` refusals that follow then count submissions Cloudflare
     * has already called a person's.
     *
     * $pass names the credential a caller that is not a person's browser carries,
     * which the site checked before this call (PASSES above). It stands in for
     * Cloudflare's word and for nothing else.
     *
     * @throws FormGuardRefused
     */
    public static function admit(
        string $form,
        array $session,
        array $post,
        array $server,
        ?int $now = null,
        ?string $pass = null
    ): void {
        if ($pass !== null && preg_match('/^[a-z][a-z0-9-]{0,39}$/', $pass) !== 1) {
            throw new InvalidArgumentException('FormGuard::admit was given a pass with no plain name');
        }
        $reason = self::check($session, $post, $now);
        if ($reason !== null) {
            self::record($form, $reason, $server);
            throw new FormGuardRefused(self::REFUSED, $reason);
        }

        if ($pass !== null) {
            // Written whether or not the check is on, so the count reads the same
            // before and after the widget's keys are set.
            self::recordPass($form, $pass, $server);
            return;
        }

        $human = self::humanCheck();
        if (!$human->isOn()) {
            return;
        }
        $verdict = $human->verify($post[HumanCheck::TOKEN_FIELD] ?? null, self::clientIp($server));
        if ($verdict['ok'] !== true) {
            self::record($form, 'no_human', $server, null, $verdict['detail']);
            throw new FormGuardRefused(self::NO_HUMAN, 'no_human');
        }
    }

    /** Tests point these at temporary files. Null means the real logs. */
    public static ?string $logFileOverride = null;
    public static ?string $passLogFileOverride = null;

    /** Most of the pass log one count reads: a log this large already says a pass leaked. */
    private const PASS_LOG_READ_BYTES = 1048576;

    /** Where refusals are written. One JSON object per line. */
    public static function logFile(): string
    {
        return self::$logFileOverride ?? self::logDirectory() . '/form-guard.jsonl';
    }

    /** Where passes are written (PASSES above). One JSON object per line. */
    private static function passLogFile(): string
    {
        return self::$passLogFileOverride ?? self::logDirectory() . '/form-guard-passes.jsonl';
    }

    private static function logDirectory(): string
    {
        // Env override for the reason SignupAttemptLog has SIGNUP_ATTEMPT_LOGDIR:
        // the HTTP tests run the real endpoints in CHILD `php -S` processes, which
        // a setter cannot reach, and without it every test run would append
        // synthetic refusals to the real evidence. tests/bootstrap.php sets it.
        $dir = (string) (getenv('FORM_GUARD_LOGDIR') ?: '');
        if ($dir !== '') {
            return rtrim($dir, "/\\");
        }
        return self::$logDirectory ?? dirname(__DIR__) . '/logs';
    }

    /**
     * Write one refusal. Never throws: a log that cannot be written must not take
     * the page down with it, so the failure goes to the PHP error log instead,
     * where the error-log sentinel reads it.
     *
     * $detail is what a reason alone does not say. `no_human` uses it to tell
     * "Cloudflare said no" from "Cloudflare could not be asked", which are the
     * guard working and this server failing, under one reason.
     */
    public static function record(
        string $form,
        string $reason,
        array $server,
        ?string $logFile = null,
        ?string $detail = null
    ): bool {
        $entry = [
            'ts'     => gmdate('Y-m-d\TH:i:s\Z'),
            'form'   => $form,
            'reason' => $reason,
            'ip'     => self::clientIp($server),
            'agent'  => self::agent($server),
        ];
        if ($detail !== null) {
            $entry['detail'] = substr($detail, 0, 160);
        }
        return self::append($logFile ?? self::logFile(), $entry, 'refusal');
    }

    /** One use of a pass: written, never thrown, as record() is. */
    private static function recordPass(string $form, string $pass, array $server): bool
    {
        return self::append(self::passLogFile(), [
            'ts'    => gmdate('Y-m-d\TH:i:s\Z'),
            'form'  => $form,
            'pass'  => $pass,
            'ip'    => self::clientIp($server),
            'agent' => self::agent($server),
        ], 'pass');
    }

    /**
     * Passes written inside the last $windowSeconds, for the health answer. 0
     * when no pass was ever written (the log does not exist yet); null when the
     * log is there and cannot be read, because "could not look" must never read
     * as "none". Only the last PASS_LOG_READ_BYTES are read: past that the count
     * is a floor, and a floor that large is already far above the alarm.
     */
    public static function countPasses(int $windowSeconds = 86400, ?int $now = null): ?int
    {
        $file = self::passLogFile();
        if (!file_exists($file)) {
            return 0;
        }
        $handle = is_file($file) && is_readable($file) ? fopen($file, 'rb') : false;
        if ($handle === false) {
            error_log('FormGuard could not read its pass log: ' . $file);
            return null;
        }
        $size = (int) (fstat($handle)['size'] ?? 0);
        if ($size > self::PASS_LOG_READ_BYTES) {
            fseek($handle, -self::PASS_LOG_READ_BYTES, SEEK_END);
            fgets($handle);   // the line the seek landed inside
        }
        $cutoff = ($now ?? time()) - $windowSeconds;
        $count = 0;
        while (($line = fgets($handle)) !== false) {
            $entry = json_decode($line, true);
            $at = is_array($entry) && is_string($entry['ts'] ?? null) ? strtotime($entry['ts']) : false;
            if ($at !== false && $at >= $cutoff) {
                $count++;
            }
        }
        fclose($handle);
        return $count;
    }

    private static function agent(array $server): ?string
    {
        return isset($server['HTTP_USER_AGENT']) && is_string($server['HTTP_USER_AGENT'])
            ? substr($server['HTTP_USER_AGENT'], 0, 160)
            : null;
    }

    /** One JSON line onto $logFile, which $what names in the error log. Never throws. */
    private static function append(string $logFile, array $entry, string $what): bool
    {
        $line = json_encode($entry, JSON_UNESCAPED_SLASHES | JSON_INVALID_UTF8_SUBSTITUTE);

        $directory = dirname($logFile);
        if (!is_dir($directory) && !@mkdir($directory, 0750, true) && !is_dir($directory)) {
            error_log('FormGuard could not create its log directory: ' . $directory);
            return false;
        }
        // The @ keeps a failed write's warning off the visitor's page. It hides
        // nothing: the result is checked on the same line and the warning's own
        // text (permission, a full disk, a path that is a directory) goes into
        // the error log with the path, so the cause is never lost.
        error_clear_last();
        // silent-failure:ignore — checked below, and logged with its cause
        if ($line === false || @file_put_contents($logFile, $line . PHP_EOL, FILE_APPEND | LOCK_EX) === false) {
            $cause = $line === false
                ? 'the entry could not be encoded as JSON'
                : (error_get_last()['message'] ?? 'PHP gave no reason');
            error_log('FormGuard could not write its ' . $what . ' log: ' . $logFile . ' (' . $cause . ')');
            return false;
        }
        return true;
    }
}
