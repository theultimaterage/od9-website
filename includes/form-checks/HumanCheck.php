/**
 * HumanCheck — asks Cloudflare whether a person sent this form (Turnstile).
 *
 * WHY THIS CLASS EXISTS
 * ---------------------
 * FormGuard's own checks ask "did a browser load this page and run its script?".
 * The program of 26 November 2026 was a browser: an automated Chrome, sent
 * through Tor, that loaded the page, waited, ran the script and posted the form.
 * Nothing this site can measure by itself tells that Chrome from a fan's. Cloudflare's
 * widget runs its own challenges in the visitor's browser and hands the form a
 * token; this class sends that token to Cloudflare and believes only the answer.
 *
 * FormGuard owns the refusal (reason `no_human`); this class owns the question.
 *
 * SOURCES — Cloudflare's own pages, read on 2026-11-26 for the band site and again on
 * 2026-11-27 for the engine, unchanged in every point below. Nothing below is from memory.
 * ------------------------------------------------------------------------------------
 *   https://developers.cloudflare.com/turnstile/
 *   https://developers.cloudflare.com/turnstile/get-started/
 *   https://developers.cloudflare.com/turnstile/concepts/widget/
 *       Turnstile is hosted under challenges.cloudflare.com. A widget is a sitekey
 *       (public, goes in the page) and a secret key (private, stays on the server).
 *   https://developers.cloudflare.com/turnstile/get-started/client-side-rendering/
 *       The script is https://challenges.cloudflare.com/turnstile/v0/api.js, loaded
 *       from exactly that address (a proxied or cached copy stops working).
 *       Explicit rendering: api.js?render=explicit&onload=<function>, then
 *       turnstile.render("#container", {sitekey: ...}) returns a widget id and
 *       turnstile.reset(widgetId) asks for a fresh token. A widget inside a <form>
 *       adds an invisible input named cf-turnstile-response, sent with the form.
 *   https://developers.cloudflare.com/turnstile/get-started/client-side-rendering/widget-configurations/
 *       size: normal 300x65, flexible 100% wide (300 at least) x 65, compact
 *       150x140 (this site uses normal, and compact where a form is narrower
 *       than 300). theme: auto, light, dark (dark here, as the site is). A
 *       token that expires is refreshed by the widget (refresh-expired: auto,
 *       the default).
 *   https://developers.cloudflare.com/turnstile/get-started/server-side-validation/
 *       POST https://challenges.cloudflare.com/turnstile/v0/siteverify, form-encoded
 *       or JSON, always answered in JSON. Fields: secret and response (required),
 *       remoteip and idempotency_key (optional). A token is at most 2048
 *       characters, lives 300 seconds and is meant for one validation. The answer
 *       carries `success` (boolean) and `error-codes`: missing-input-secret,
 *       invalid-input-secret, missing-input-response, invalid-input-response,
 *       bad-request, timeout-or-duplicate, internal-error. "Set reasonable
 *       timeouts. Do not wait indefinitely for Siteverify responses."
 *   https://developers.cloudflare.com/turnstile/troubleshooting/testing/
 *       The published test keys (tests/support/TurnstileTestKeys.php holds them;
 *       no class the site loads does). They work on any domain, localhost
 *       included; a test sitekey yields the token XXXX.DUMMY.TOKEN.XXXX, which
 *       only a test secret accepts, and a real secret refuses it. The page now also
 *       lists invisible test sitekeys and one that forces an interactive challenge;
 *       they share the shape usesTestKeys() looks for.
 *   https://developers.cloudflare.com/turnstile/reference/content-security-policy/
 *       A site that sends a Content-Security-Policy adds
 *       https://challenges.cloudflare.com to script-src and to frame-src.
 *
 * THE KEYS
 * --------
 * Two lines in the account's .env, which the site loads into the process (the
 * engine's core/Environment.php does it for the platform and every store), read
 * here with getenv(). Never written in a repository, never printed, never logged.
 * The sitekey is public by design: it is in the page.
 *
 *   TURNSTILE_SITEKEY      the widget's sitekey
 *   TURNSTILE_SECRET_KEY   the widget's secret key
 *
 * WITH NO KEY THE CHECK IS OFF and every form behaves as it did before this class
 * existed, so the code can be deployed before the widget is created. With one key
 * and not the other it is MISCONFIGURED: it cannot run, so it does not, and the
 * health endpoint answers FAIL until the second key is set. With Cloudflare's
 * published TEST keys it runs and passes everyone, which is what a developer's
 * machine wants and the live site must never have: the health endpoint answers
 * FAIL and says `test_keys`, never `on`.
 *
 * WHEN CLOUDFLARE CANNOT BE ASKED THE FORM IS REFUSED. A check that lets everyone
 * through whenever it cannot reach its judge is a check a program switches off.
 * The cost is honest too: a real outage refuses real people, so every such
 * refusal is written to the PHP error log with its cause (the error-log sentinel
 * reads that), and the refusal's line in logs/form-guard.jsonl says `unreachable`.
 *
 * HOW CLOUDFLARE IS ASKED: through the transport the site hands in. This file
 * holds no network code, so each site asks the way its own rules require: the
 * engine through SsrfGuard, its one outbound transport (core/HumanCheckTransport.php,
 * handed to FormGuard::configure() by PublicBootstrap; the engine's SsrfGuardTest
 * refuses any other), and the band site and od9 through their own when their
 * copies are made (pieces 4 and 6). A check given no transport cannot ask, so it
 * refuses, with that cause in the error log.
 */
final class HumanCheck
{
    public const SITE_KEY_ENV = 'TURNSTILE_SITEKEY';
    public const SECRET_KEY_ENV = 'TURNSTILE_SECRET_KEY';

    public const ORIGIN = 'https://challenges.cloudflare.com';
    public const SCRIPT_URL = self::ORIGIN . '/turnstile/v0/api.js';
    public const SITEVERIFY_URL = self::ORIGIN . '/turnstile/v0/siteverify';

    /** The input the widget adds to its form. */
    public const TOKEN_FIELD = 'cf-turnstile-response';
    public const MAX_TOKEN_LENGTH = 2048;

    /** Seconds to open the connection, and seconds for the whole question. */
    public const CONNECT_TIMEOUT_SECONDS = 3;
    public const TIMEOUT_SECONDS = 6;

    public const OFF = 'off';
    public const ON = 'on';
    public const MISCONFIGURED = 'misconfigured';
    /** On, but the page's Content-Security-Policy would stop the widget loading. */
    public const BLOCKED = 'blocked';
    /** On, with Cloudflare's published test keys: it passes every visitor and every program. */
    public const TEST_KEYS = 'test_keys';

    private string $siteKey;
    private string $secretKey;

    /** @var callable(string, array<string, string>, int, int): string */
    private $http;

    /**
     * @param callable|null $http (url, fields, connect seconds, total seconds) => response body.
     *                            It throws when no answer came back. The site hands in its
     *                            transport (HOW CLOUDFLARE IS ASKED); null asks nobody and refuses.
     */
    public function __construct(string $siteKey, string $secretKey, ?callable $http = null)
    {
        $this->siteKey = trim($siteKey);
        $this->secretKey = trim($secretKey);
        $this->http = $http ?? self::noTransport();
    }

    /** The check as this server is configured: both keys from the process environment. */
    public static function fromEnvironment(?callable $http = null): self
    {
        $site = getenv(self::SITE_KEY_ENV);
        $secret = getenv(self::SECRET_KEY_ENV);

        return new self(is_string($site) ? $site : '', is_string($secret) ? $secret : '', $http);
    }

    /** OFF, ON or MISCONFIGURED. Only ON prints a widget or asks Cloudflare anything. */
    public function state(): string
    {
        if ($this->siteKey === '' && $this->secretKey === '') {
            return self::OFF;
        }
        if ($this->siteKey !== '' && $this->secretKey !== '') {
            return self::ON;
        }
        return self::MISCONFIGURED;
    }

    public function isOn(): bool
    {
        return $this->state() === self::ON;
    }

    /**
     * Is either key one of Cloudflare's published test keys? They are a "1x",
     * "2x" or "3x", then nothing but zeros, then two capital letters; a real key
     * looks nothing like that. With them the widget draws and every token
     * passes, which is right on a developer's machine and, on the live site, a
     * human check that checks nobody while every sign says it is on.
     */
    public function usesTestKeys(): bool
    {
        $shape = '/^[123]x0{16,}[A-Z]{2}$/';

        return preg_match($shape, $this->siteKey) === 1 || preg_match($shape, $this->secretKey) === 1;
    }

    /**
     * state(), for the health endpoint, which must not answer "on" for a check
     * that cannot work: TEST_KEYS when it runs on Cloudflare's test keys, BLOCKED
     * when the policy file on this server does not allow its widget or cannot
     * be read. A check that is off or misconfigured is answered as it is, and
     * the file is not opened.
     *
     * $policyFile is the file that builds the Content-Security-Policy the site's
     * form pages send, or null for a site whose form pages send none: nothing
     * can block the widget then, and that site's own test proves the null true
     * (the engine's PublicFormsUseTheGuardTest does it for the platform).
     */
    public function stateBehind(?string $policyFile): string
    {
        $state = $this->state();
        if ($state !== self::ON) {
            return $state;
        }
        if ($this->usesTestKeys()) {
            return self::TEST_KEYS;
        }
        if ($policyFile === null) {
            return self::ON;
        }

        $policy = is_file($policyFile) && is_readable($policyFile) ? file_get_contents($policyFile) : false;

        return is_string($policy) && self::policyAllowsWidget(self::withoutComments($policy)) ? self::ON : self::BLOCKED;
    }

    /**
     * PHP source with its comments removed, so a comment that NAMES a directive
     * (the policy file explains itself in several) is never read as the policy.
     */
    private static function withoutComments(string $source): string
    {
        if (!function_exists('token_get_all') || strpos($source, '<?php') === false) {
            return $source;
        }
        $code = '';
        foreach (token_get_all($source) as $token) {
            if (is_array($token)) {
                if ($token[0] !== T_COMMENT && $token[0] !== T_DOC_COMMENT) {
                    $code .= $token[1];
                }
            } else {
                $code .= $token;
            }
        }
        return $code;
    }

    /**
     * The widget's place inside one form. Empty unless the check is on.
     *
     * No `cf-turnstile` class on purpose: that class is for implicit rendering,
     * and this site renders explicitly (see script()) so that it holds each
     * widget's id and can ask for a fresh token after a form posted without
     * leaving the page.
     */
    public function widget(): string
    {
        if (!$this->isOn()) {
            return '';
        }

        // A row of its form with the widget centred in it, and the widget's
        // height held open so the button below does not jump when it arrives.
        return '<div class="fg-human" data-sitekey="' . htmlspecialchars($this->siteKey, ENT_QUOTES, 'UTF-8')
            . '" style="display:flex;justify-content:center;width:100%;min-height:65px;margin:0 0 1rem;"></div>';
    }

    /**
     * Cloudflare's script and the few lines that put a widget in every place
     * widget() printed. Once per page. Empty unless the check is on.
     *
     * A widget is rendered when its place first comes into view, never while it
     * is hidden: the home page's popup form is display:none until it opens, and a
     * challenge is not started in a box nobody can see. window.fgHuman.reset(form)
     * asks for a fresh token; a page that posts a form with fetch() and stays put
     * calls it after a refusal, because a token is good for one question only.
     */
    public function script(): string
    {
        if (!$this->isOn()) {
            return '';
        }

        return '<script>(function(){var count=0;'
            // One widget into one place, once. The place gets an id because
            // turnstile.render() is documented with a selector.
            . 'function show(el){if(el.getAttribute("data-fg-widget")){return;}'
            . 'if(!el.id){count++;el.id="fg-human-"+count;}'
            // 300 pixels wide where there is room for it, the 150-pixel one
            // where there is not (a small phone's popup).
            . 'try{var id=turnstile.render("#"+el.id,{sitekey:el.getAttribute("data-sitekey"),theme:"dark",'
            . 'size:(el.clientWidth&&el.clientWidth<300)?"compact":"normal"});'
            . 'if(id){el.setAttribute("data-fg-widget",id);}}'
            . 'catch(e){if(window.console){console.error(e);}}}'
            // Called by api.js when it has loaded (its onload parameter).
            . 'window.fgHumanReady=function(){var all=document.querySelectorAll(".fg-human"),i;'
            . 'if(!("IntersectionObserver" in window)){for(i=0;i<all.length;i++){show(all[i]);}return;}'
            . 'var watch=new IntersectionObserver(function(entries){for(var j=0;j<entries.length;j++){'
            . 'if(entries[j].isIntersecting){watch.unobserve(entries[j].target);show(entries[j].target);}}},'
            . '{rootMargin:"400px"});'
            . 'for(i=0;i<all.length;i++){watch.observe(all[i]);}};'
            . 'window.fgHuman={reset:function(form){var el=form&&form.querySelector?form.querySelector(".fg-human"):null;'
            . 'var id=el?el.getAttribute("data-fg-widget"):null;if(id&&window.turnstile){turnstile.reset(id);}}};'
            . '})();</script>'
            . '<script src="' . self::SCRIPT_URL . '?render=explicit&amp;onload=fgHumanReady" defer></script>';
    }

    /**
     * Ask Cloudflare about one token.
     *
     * `detail` is for the operator's log, never for the visitor: `missing` (the
     * form carried no token), `malformed` (longer than a token can be),
     * `rejected:<Cloudflare's error codes>`, `unreachable` (no answer came back)
     * or `unreadable` (an answer that is not Cloudflare's JSON). Every one of them
     * is a refusal; the last two, and a secret Cloudflare does not accept, are OUR
     * fault and go to the PHP error log as well.
     *
     * @param mixed $token whatever the form sent under TOKEN_FIELD
     * @return array{ok: bool, detail: string}
     */
    public function verify($token, ?string $remoteIp = null): array
    {
        if (!$this->isOn()) {
            // Nothing to ask with. Callers check isOn() first; this answer keeps
            // a caller that forgot from refusing every visitor of a site whose
            // check was never switched on.
            return ['ok' => true, 'detail' => $this->state()];
        }
        if (!is_string($token) || trim($token) === '') {
            return ['ok' => false, 'detail' => 'missing'];
        }
        if (strlen($token) > self::MAX_TOKEN_LENGTH) {
            return ['ok' => false, 'detail' => 'malformed'];
        }

        $fields = ['secret' => $this->secretKey, 'response' => $token];
        if ($remoteIp !== null && filter_var($remoteIp, FILTER_VALIDATE_IP) !== false) {
            $fields['remoteip'] = $remoteIp;
        }

        try {
            $body = ($this->http)(self::SITEVERIFY_URL, $fields, self::CONNECT_TIMEOUT_SECONDS, self::TIMEOUT_SECONDS);
        } catch (Throwable $e) {
            // The message is the transport's own (a timeout, a refused connection,
            // a certificate). It never holds the secret or the token: neither is
            // part of the address, and the caller builds no message from the body
            // it sent.
            error_log('HumanCheck could not reach Cloudflare siteverify, so a form was refused: ' . $e->getMessage());
            return ['ok' => false, 'detail' => 'unreachable'];
        }

        $answer = is_string($body) ? json_decode($body, true) : null;
        if (!is_array($answer) || !is_bool($answer['success'] ?? null)) {
            error_log('HumanCheck got an answer from Cloudflare siteverify that is not its JSON, so a form was refused');
            return ['ok' => false, 'detail' => 'unreadable'];
        }
        if ($answer['success'] === true) {
            return ['ok' => true, 'detail' => 'passed'];
        }

        $codes = [];
        foreach ((array) ($answer['error-codes'] ?? []) as $code) {
            if (is_string($code) && preg_match('/^[a-z0-9-]{1,40}$/', $code) === 1) {
                $codes[] = $code;
            }
        }
        if (array_intersect($codes, ['missing-input-secret', 'invalid-input-secret']) !== []) {
            error_log('HumanCheck: Cloudflare does not accept this site\'s ' . self::SECRET_KEY_ENV
                . ', so every form is refusing every visitor');
        }

        return ['ok' => false, 'detail' => 'rejected:' . ($codes === [] ? 'no-code' : implode(',', array_slice($codes, 0, 4)))];
    }

    /**
     * Does this Content-Security-Policy let the widget load?
     *
     * Cloudflare's CSP page asks for exactly two things: its origin in script-src
     * and in frame-src. $policy is a header's value, or the text of a PHP file
     * that builds one with each directive as one double-quoted string (as the
     * band's private/includes/security-headers.php does), so the same reading
     * works on both: a directive ends at a semicolon or at the string's closing
     * quote. A site's health endpoint asks this of the file ON ITS SERVER, which
     * the deploy may not carry: a check that is on behind a policy that blocks
     * its widget refuses every visitor, and nothing else would say so.
     *
     * It reads the two directives Cloudflare names and nothing else. A policy
     * with no frame-src of its own, leaning on default-src, is answered "no".
     */
    public static function policyAllowsWidget(string $policy): bool
    {
        foreach (['script-src', 'frame-src'] as $directive) {
            if (preg_match_all('/(?<![a-z-])' . $directive . '\s+([^;"]*)/i', $policy, $found) < 1) {
                return false;
            }
            $allowed = false;
            foreach ($found[1] as $sources) {
                if (in_array(self::ORIGIN, preg_split('/\s+/', trim($sources)), true)) {
                    $allowed = true;
                }
            }
            if (!$allowed) {
                return false;
            }
        }
        return true;
    }

    /**
     * What a check built without a transport asks with: nothing. It throws, so
     * verify() refuses the form and writes the cause to the error log: a site
     * that forgot its transport refuses everyone rather than passing everyone.
     *
     * @return callable(string, array<string, string>, int, int): string
     */
    private static function noTransport(): callable
    {
        return static function (): string {
            throw new RuntimeException(
                'HumanCheck was given no transport: the site did not hand one to FormGuard::configure()'
            );
        };
    }
}
