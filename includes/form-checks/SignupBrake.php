/**
 * SignupBrake — the site stops taking signups while the ones it has taken go unconfirmed.
 *
 * WHY THIS CLASS EXISTS
 * ---------------------
 * Every signup makes this site send a confirmation message to whatever address
 * was typed. FormGuard refuses the programs it can recognise, and says in its own
 * header that it does not stop one that drives a real browser slowly from many
 * addresses. SignupVolume counts what gets past and says so, but only says so.
 *
 * On 26 November 2026 that program came back: two dozen signups in under a day
 * through the home page's footer form, each from a different Tor exit, a little
 * under an hour apart, sent by an automated Chrome that passed every check
 * FormGuard makes. None was confirmed. SignupVolume reported it within the hour,
 * and the site went on mailing strangers while a person read the report.
 *
 * This is the part that does not wait for a person. Past the cap, the site takes
 * no new signup: no row is stored and no mail is sent.
 *
 * THE RULE
 * --------
 * Over the last 24 hours: CAP or more signups still unconfirmed, AND fewer than
 * one in CONFIRMED_ONE_IN of that window's signups confirmed.
 *
 * Replayed against that night's backup (23 rows from the footer form, the first
 * and the last 18 hours 38 minutes apart), the brake is on from the eleventh
 * signup and thirteen are refused: ten strangers mailed in a day at most,
 * whatever the program's patience, instead of as many as it cares to send.
 *
 * The brake lets go by itself: when a row is confirmed, when the old rows pass out
 * of the window, or when the unconfirmed rows are deleted (on the band site, its
 * private/cron/purge-unconfirmed-signups.php).
 *
 * WHAT IT COSTS, said plainly
 * ---------------------------
 * A real surge trips it too. Ten fans who sign up at a show inside one day and
 * have not opened their mail yet hold the eleventh out until two of them confirm.
 * The eleventh reads that the form was not taken and to try again tomorrow, so
 * nobody waits for mail that is not coming. Before the first flood the form took
 * 22 signups in six months; ten unconfirmed in a day has never been a normal day.
 *
 * ON THE PLATFORM (27 November 2026) the same rule stands in front of
 * api/signup/register.php, the door every new store comes through, which mails a
 * verification to the address typed. Its table is email_signups, with the same
 * two columns; a signup is confirmed when its link is clicked
 * (SignupCompletionService sets is_verified).
 *
 * A REFUSAL IS TOLD AS A REFUSAL, as FormGuard's are: the visitor reads PAUSED,
 * the refusal is one line in logs/form-guard.jsonl with the reason `paused`, and
 * public/api/health/signup-volume.php answers FAIL with `"paused": true`, which
 * the hourly check reads.
 *
 * judge() is pure, so the rule is proved at its edges without a database.
 * count() compares rows with the DATABASE's own clock on both sides: it is
 * SignupVolume's count over a shorter window, one query for both, so the brake
 * and the alarm can never count the same table two ways.
 */

require_once __DIR__ . '/FormGuard.php';
require_once __DIR__ . '/SignupVolume.php';

final class SignupBrake
{
    public const WINDOW_SECONDS = 86400;

    /** Unconfirmed signups inside the window at which the brake can go on. */
    public const CAP = 10;

    /** At the cap the brake goes on unless at least one signup in this many was confirmed. */
    public const CONFIRMED_ONE_IN = 5;

    /** Passes in a day above which the health answer fails: the provers make one or two. */
    public const PASSES_ALARM_AT = 10;

    public const PAUSED = "We're not taking new signups right now, so yours was not saved and no email was sent. "
        . 'Please try again tomorrow.';

    /**
     * @return array{paused: bool, unconfirmed: int, reason: string}
     */
    public static function judge(int $signups, int $confirmed): array
    {
        $hours = intdiv(self::WINDOW_SECONDS, 3600);

        if ($signups < 0 || $confirmed < 0 || $confirmed > $signups) {
            // The count is one query. If it ever answers this, the brake cannot
            // tell how many strangers the site has mailed, so it holds: a brake
            // that lets go when it cannot see is the failure this class exists
            // to end. The health endpoint carries the reason.
            return [
                'paused'      => true,
                'unconfirmed' => 0,
                'reason'      => "the counts make no sense ({$signups} signups, {$confirmed} confirmed): "
                    . 'the brake cannot see, so it holds',
            ];
        }

        $unconfirmed = $signups - $confirmed;
        // Whole numbers on both sides: "fewer than one in five" is
        // confirmed * 5 < signups, with no fraction to round.
        $paused = $unconfirmed >= self::CAP && $confirmed * self::CONFIRMED_ONE_IN < $signups;

        return [
            'paused'      => $paused,
            'unconfirmed' => $unconfirmed,
            'reason'      => $paused
                ? "{$signups} signups in {$hours} hours and {$confirmed} confirmed (the brake is at "
                    . self::CAP . ' unconfirmed)'
                : "{$signups} signups in {$hours} hours, {$confirmed} confirmed",
        ];
    }

    /**
     * Signups and confirmations inside the brake's window, on the database's clock.
     *
     * @return array{signups: int, confirmed: int}
     */
    public static function count(PDO $pdo, int $windowSeconds = self::WINDOW_SECONDS): array
    {
        return SignupVolume::count($pdo, $windowSeconds);
    }

    /**
     * For a page: when the brake is on, the refusal is logged and thrown before
     * the handler stores a row or sends a message.
     *
     * Call it once the database is open and BEFORE the per-sender limit, so a
     * visitor turned away by the brake is told the truth (try again tomorrow)
     * and not that their own connection made too many attempts.
     *
     * @throws FormGuardRefused
     */
    public static function admit(string $form, PDO $pdo, array $server): void
    {
        $counts = self::count($pdo);
        $verdict = self::judge($counts['signups'], $counts['confirmed']);

        if ($verdict['paused']) {
            FormGuard::record($form, 'paused', $server);
            throw new FormGuardRefused(self::PAUSED, 'paused');
        }
    }

    /**
     * What public/api/health/signup-volume.php answers: SignupVolume's seven-day
     * verdict, whether the brake is on, and whether the human check is running.
     *
     * Pure, so every combination is proved in a test. The pause is said FIRST in
     * the reason: the hourly check keeps 180 characters of it.
     *
     * @param array{signups: int, confirmed: int} $week       SignupVolume::count()
     * @param array{signups: int, confirmed: int} $day        SignupBrake::count()
     * @param string                              $humanCheck HumanCheck::OFF, ON, MISCONFIGURED, BLOCKED or TEST_KEYS
     * @param int|null                            $passes     FormGuard::countPasses(): passes in the last day,
     *                                                        null when the pass log could not be read
     * @return array<string, mixed>
     */
    public static function health(array $week, array $day, string $humanCheck, ?int $passes): array
    {
        $volume = SignupVolume::judge($week['signups'], $week['confirmed']);
        $brake = self::judge($day['signups'], $day['confirmed']);

        $problems = [];
        if ($brake['paused']) {
            $problems[] = 'the site has stopped taking signups: ' . $brake['reason'];
        }
        if ($humanCheck === HumanCheck::MISCONFIGURED) {
            $problems[] = 'the human check has one of its two keys and not the other ('
                . HumanCheck::SITE_KEY_ENV . ', ' . HumanCheck::SECRET_KEY_ENV . '), so it is not running';
        } elseif ($humanCheck === HumanCheck::BLOCKED) {
            $problems[] = "the human check is on but this server's Content-Security-Policy does not allow "
                . "Cloudflare's widget, so every form is refusing every visitor";
        } elseif ($humanCheck === HumanCheck::TEST_KEYS) {
            $problems[] = "the human check is running on Cloudflare's published test keys, which pass every "
                . 'visitor and every program';
        } elseif ($humanCheck !== HumanCheck::OFF && $humanCheck !== HumanCheck::ON) {
            $problems[] = "the human check answered a state this endpoint does not know ('{$humanCheck}')";
        }
        if ($passes === null) {
            $problems[] = "the guard's pass log could not be read, so nobody can tell whether a pass leaked";
        } elseif ($passes > self::PASSES_ALARM_AT) {
            $problems[] = "{$passes} passes in a day, more than the provers make: a pass may have leaked";
        }
        if ($volume['status'] !== 'OK') {
            $problems[] = $volume['reason'];
        }

        return [
            'status'           => $problems === [] ? 'OK' : 'FAIL',
            'signups'          => $week['signups'],
            'confirmed'        => $week['confirmed'],
            'window_days'      => intdiv(SignupVolume::WINDOW_SECONDS, 86400),
            'reason'           => $problems === [] ? $volume['reason'] : implode('; ', $problems),
            'paused'           => $brake['paused'],
            'recent_signups'   => $day['signups'],
            'recent_confirmed' => $day['confirmed'],
            'recent_hours'     => intdiv(self::WINDOW_SECONDS, 3600),
            'human_check'      => $humanCheck,
            'passes_24h'       => $passes,
        ];
    }
}
