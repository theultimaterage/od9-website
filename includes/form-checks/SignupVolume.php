/**
 * SignupVolume — says so when the email list is filling faster than fans fill it.
 *
 * WHY THIS CLASS EXISTS
 * ---------------------
 * FormGuard refuses the programs it can recognise. It cannot recognise one that
 * drives a real browser slowly from many addresses, and the flood of July to
 * September 2026 was exactly that patient: 624 signups through one form over ten
 * weeks, never more than eight in a minute, some weeks only five to nine a day.
 * Nothing counted them, so nothing noticed.
 *
 * This counts them. It is the half of the fix that does not depend on out-guessing
 * the program: whatever gets past the guard still shows up here as rows nobody
 * confirms.
 *
 * THE RULE
 * --------
 * Over the last seven days: ALARM_AT signups or more, with fewer than one in five
 * confirmed. Before the flood the form took 22 signups in six months, so ten in a
 * week is already far outside anything the band has seen. During the flood 23 of
 * 672 were confirmed (3%), and every week of it would have tripped this, the slow
 * ones included: the quietest week still brought 19.
 *
 * A real surge trips it too, for as long as the confirmations lag behind: the
 * night a QR code goes up at a show, this will say so. That is on purpose. Ten
 * people joining in a week is news either way, and the reason line says which
 * numbers to look at.
 *
 * On the platform (27 November 2026) the same rule watches the store signups of
 * api/signup/register.php, kept in a table of the same name and columns.
 *
 * judge() is pure, so the rule is proved in a test without a database. count()
 * compares rows with the DATABASE's own clock, for the reason FormGuard does.
 */
final class SignupVolume
{
    public const WINDOW_SECONDS = 7 * 86400;

    /** Signups inside the window before the confirmed share is judged at all. */
    public const ALARM_AT = 10;

    /** At or above the alarm count, fewer than this share confirmed is the alarm. */
    public const MIN_CONFIRMED_SHARE = 0.2;

    /**
     * @return array{status: string, reason: string}
     */
    public static function judge(int $signups, int $confirmed): array
    {
        if ($signups < 0 || $confirmed < 0 || $confirmed > $signups) {
            return [
                'status' => 'FAIL',
                'reason' => "the counts make no sense ({$signups} signups, {$confirmed} confirmed): the check itself is broken",
            ];
        }

        if ($signups >= self::ALARM_AT && $confirmed < $signups * self::MIN_CONFIRMED_SHARE) {
            return [
                'status' => 'FAIL',
                'reason' => "{$signups} signups in 7 days and {$confirmed} confirmed: a program is using the form, "
                    . 'or a real surge has not confirmed yet',
            ];
        }

        return [
            'status' => 'OK',
            'reason' => "{$signups} signups in 7 days, {$confirmed} confirmed",
        ];
    }

    /**
     * @return array{signups: int, confirmed: int}
     */
    public static function count(PDO $pdo, int $windowSeconds = self::WINDOW_SECONDS): array
    {
        $dbNow = (string) $pdo->query('SELECT CURRENT_TIMESTAMP')->fetchColumn();
        $cutoff = (new DateTimeImmutable($dbNow))
            ->modify('-' . $windowSeconds . ' seconds')
            ->format('Y-m-d H:i:s');

        $statement = $pdo->prepare(
            'SELECT COUNT(*) AS signups, '
            . 'COALESCE(SUM(CASE WHEN is_verified = 1 THEN 1 ELSE 0 END), 0) AS confirmed '
            . 'FROM email_signups WHERE created_at > :cutoff'
        );
        $statement->execute(['cutoff' => $cutoff]);
        $row = $statement->fetch(PDO::FETCH_ASSOC);

        return [
            'signups'   => (int) ($row['signups'] ?? 0),
            'confirmed' => (int) ($row['confirmed'] ?? 0),
        ];
    }
}
